-- =============================================================================
-- 01_raw_tables.sql
-- RAW landing tables and the CONTROL run log. Idempotent (IF NOT EXISTS).
--
-- Design decisions
--   * Append-only. Every pipeline run inserts new rows tagged with RUN_ID, so
--     history is preserved and any run can be traced to CONTROL.PIPELINE_RUNS.
--   * Typed columns for the fields the pipeline uses today, plus RAW_PAYLOAD
--     (the untouched API item as VARIANT) so new attributes can be modelled in
--     dbt later without re-calling the API.
--   * Counts are nullable: YouTube hides like/subscriber counts on some
--     entities, and "hidden" must not be confused with zero.
--   * PRIMARY KEY constraints are informational (Snowflake does not enforce
--     them); they document the grain. The loader guarantees uniqueness.
--   * No clustering keys: volumes are small; revisit beyond ~1 TB.
-- =============================================================================

USE ROLE SYSADMIN;

-- ---------------------------------------------------------------------------
-- CONTROL.PIPELINE_RUNS - one row per pipeline execution
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS YOUTUBE_DB.CONTROL.PIPELINE_RUNS (
    RUN_ID                     VARCHAR(36)    NOT NULL COMMENT 'UUID generated by the pipeline at start',
    PIPELINE_NAME              VARCHAR(100)   NOT NULL COMMENT 'Logical pipeline name, e.g. youtube_ingestion',
    STATUS                     VARCHAR(20)    NOT NULL COMMENT 'RUNNING | SUCCEEDED | FAILED',
    STARTED_AT                 TIMESTAMP_TZ   NOT NULL COMMENT 'Run start (UTC)',
    FINISHED_AT                TIMESTAMP_TZ            COMMENT 'Run end (UTC); NULL while running',
    RUN_PARAMETERS             VARIANT                 COMMENT 'Keywords, page limits and other run inputs',
    VIDEOS_DISCOVERED          NUMBER(38,0)            COMMENT 'Unique video IDs returned by search.list',
    VIDEOS_ENRICHED            NUMBER(38,0)            COMMENT 'Videos returned by videos.list',
    CHANNELS_EXTRACTED         NUMBER(38,0)            COMMENT 'Channels returned by channels.list',
    API_QUOTA_UNITS_ESTIMATED  NUMBER(38,0)            COMMENT 'Estimated units used from the 10,000/day budget (excludes search.list)',
    ERROR_MESSAGE              VARCHAR                 COMMENT 'Failure reason when STATUS = FAILED',
    CREATED_AT                 TIMESTAMP_TZ   DEFAULT CURRENT_TIMESTAMP() COMMENT 'Row insert time',
    -- Added by migration 20261111_02 (kept last so fresh and migrated tables match)
    SEARCH_CALLS               NUMBER(38,0)            COMMENT 'search.list calls made (separate 100/day allowance)',
    CONSTRAINT PK_PIPELINE_RUNS PRIMARY KEY (RUN_ID)
)
COMMENT = 'Pipeline execution log. Grain: one row per run.';

-- ---------------------------------------------------------------------------
-- RAW.VIDEO_DISCOVERY - search.list results
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS YOUTUBE_DB.RAW.VIDEO_DISCOVERY (
    RUN_ID          VARCHAR(36)    NOT NULL COMMENT 'FK to CONTROL.PIPELINE_RUNS',
    SEARCH_KEYWORD  VARCHAR(500)   NOT NULL COMMENT 'Query sent to search.list',
    SEARCH_RANK     NUMBER(5,0)             COMMENT '1-based position in results for the keyword',
    VIDEO_ID        VARCHAR(50)    NOT NULL COMMENT 'YouTube video ID',
    CHANNEL_ID      VARCHAR(50)             COMMENT 'YouTube channel ID',
    TITLE           VARCHAR                 COMMENT 'Video title (HTML-escaped as returned by API)',
    DESCRIPTION     VARCHAR                 COMMENT 'Truncated description from search snippet',
    CHANNEL_TITLE   VARCHAR                 COMMENT 'Channel display name',
    PUBLISHED_AT    TIMESTAMP_TZ            COMMENT 'Video publish time',
    RAW_PAYLOAD     VARIANT                 COMMENT 'Untouched search result item',
    DISCOVERED_AT   TIMESTAMP_TZ   NOT NULL DEFAULT CURRENT_TIMESTAMP() COMMENT 'Extraction time (UTC)',
    -- Added by migration 20261111_03 (kept last so fresh and migrated tables match)
    SEARCH_NAME     VARCHAR(200)   NOT NULL COMMENT 'Unique name of the configured search (config/searches.toml)',
    SEARCH_FILTERS  VARIANT                 COMMENT 'Exact search.list parameters sent (q, order, regionCode, ...)',
    CONSTRAINT PK_VIDEO_DISCOVERY PRIMARY KEY (RUN_ID, SEARCH_NAME, VIDEO_ID)
)
COMMENT = 'Search results. Grain: one row per run x configured search x video.';

-- ---------------------------------------------------------------------------
-- RAW.VIDEO_SNAPSHOT - videos.list statistics at a point in time
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS YOUTUBE_DB.RAW.VIDEO_SNAPSHOT (
    RUN_ID         VARCHAR(36)    NOT NULL COMMENT 'FK to CONTROL.PIPELINE_RUNS',
    VIDEO_ID       VARCHAR(50)    NOT NULL COMMENT 'YouTube video ID',
    CHANNEL_ID     VARCHAR(50)             COMMENT 'YouTube channel ID',
    TITLE          VARCHAR                 COMMENT 'Video title',
    CATEGORY_ID    VARCHAR(20)             COMMENT 'YouTube video category ID',
    PUBLISHED_AT   TIMESTAMP_TZ            COMMENT 'Video publish time',
    DURATION       VARCHAR(50)             COMMENT 'ISO 8601 duration, e.g. PT10M5S (parsed in dbt)',
    VIEW_COUNT     NUMBER(38,0)            COMMENT 'Views at snapshot time',
    LIKE_COUNT     NUMBER(38,0)            COMMENT 'Likes at snapshot time; NULL if hidden',
    COMMENT_COUNT  NUMBER(38,0)            COMMENT 'Comments at snapshot time; NULL if disabled',
    RAW_PAYLOAD    VARIANT                 COMMENT 'Untouched videos.list item',
    SNAPSHOT_AT    TIMESTAMP_TZ   NOT NULL DEFAULT CURRENT_TIMESTAMP() COMMENT 'Extraction time (UTC)',
    CONSTRAINT PK_VIDEO_SNAPSHOT PRIMARY KEY (RUN_ID, VIDEO_ID)
)
COMMENT = 'Video statistics snapshots. Grain: one row per run x video.';

-- ---------------------------------------------------------------------------
-- RAW.CHANNEL_SNAPSHOT - channels.list statistics at a point in time
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS YOUTUBE_DB.RAW.CHANNEL_SNAPSHOT (
    RUN_ID               VARCHAR(36)    NOT NULL COMMENT 'FK to CONTROL.PIPELINE_RUNS',
    CHANNEL_ID           VARCHAR(50)    NOT NULL COMMENT 'YouTube channel ID',
    CHANNEL_NAME         VARCHAR                 COMMENT 'Channel display name',
    PUBLISHED_AT         TIMESTAMP_TZ            COMMENT 'Channel creation time',
    SUBSCRIBER_COUNT     NUMBER(38,0)            COMMENT 'Subscribers (rounded by YouTube); NULL if hidden',
    TOTAL_VIEWS          NUMBER(38,0)            COMMENT 'Lifetime channel views',
    VIDEO_COUNT          NUMBER(38,0)            COMMENT 'Public videos on the channel',
    UPLOADS_PLAYLIST_ID  VARCHAR(100)            COMMENT 'Playlist containing all channel uploads',
    RAW_PAYLOAD          VARIANT                 COMMENT 'Untouched channels.list item',
    SNAPSHOT_AT          TIMESTAMP_TZ   NOT NULL DEFAULT CURRENT_TIMESTAMP() COMMENT 'Extraction time (UTC)',
    CONSTRAINT PK_CHANNEL_SNAPSHOT PRIMARY KEY (RUN_ID, CHANNEL_ID)
)
COMMENT = 'Channel statistics snapshots. Grain: one row per run x channel.';
